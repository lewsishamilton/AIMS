/** dd/mm/yyyy from an <input type="date"> value. */
export function formatDate(iso: string): string {
  if (!iso) return "";
  const [y, m, d] = iso.split("-");
  return `${d}/${m}/${y}`;
}

/** Whole years and months between two <input type="date"> values; null if incomplete or reversed. */
export function durationBetween(from: string, to: string): { years: number; months: number } | null {
  if (!from || !to) return null;
  const a = new Date(from);
  const b = new Date(to);
  if (Number.isNaN(a.getTime()) || Number.isNaN(b.getTime()) || b < a) return null;
  let months = (b.getFullYear() - a.getFullYear()) * 12 + (b.getMonth() - a.getMonth());
  if (b.getDate() < a.getDate()) months -= 1;
  months = Math.max(0, months);
  return { years: Math.floor(months / 12), months: months % 12 };
}

export const durationText = (from: string, to: string) => {
  const d = durationBetween(from, to);
  return d ? `${d.years} (y) ${d.months} (m)` : "";
};

const today = () => {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, "0")}/${String(d.getMonth() + 1).padStart(2, "0")}/${d.getFullYear()}`;
};

/** "Assistant Professor – General Medicine" */
export const postTitle = (a: Pick<FacultyApplication, "post" | "department">) =>
  [a.post, a.department].filter(Boolean).join(" – ");

/** Safe file name part from the candidate's name. */
export const fileSlug = (s: string) =>
  s.trim().replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 40) || "Applicant";

/**
 * Build the application PDF: the printed form's sections in order, with the applicant's
 * photo where the form says "affix photo". `photo` is a JPEG data URL.
 */
export async function buildApplicationPdf(a: FacultyApplication, photo: string): Promise<Blob> {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const M = 14;
  const NAVY: [number, number, number] = [31, 51, 81];

  // Letterhead
  doc.setFont("times", "bold");
  doc.setFontSize(15);
  doc.setTextColor(...NAVY);
  doc.text("ARUNDATHI INSTITUTE OF MEDICAL SCIENCES", W / 2, 16, { align: "center" });
  doc.setFontSize(9.5);
  doc.setTextColor(40);
  doc.text("Dundigal, Gandimaisamma, Medchal Road, Hyderabad-500043, Telangana", W / 2, 22, { align: "center" });
  doc.setDrawColor(40);
  doc.setLineWidth(0.4);
  doc.line(M, 26, W - M, 26);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(11.5);
  doc.setTextColor(0);
  doc.text("APPLICATION FOR FACULTY RECRUITMENT", W / 2, 34, { align: "center" });

  // Passport photo, top right (35 x 45 mm)
  const photoW = 30;
  const photoH = 38;
  try {
    doc.addImage(photo, "JPEG", W - M - photoW, 39, photoW, photoH);
  } catch {
    /* a broken image should not block the application */
  }
  doc.setDrawColor(120);
  doc.rect(W - M - photoW, 39, photoW, photoH);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Application for the post of:", M, 44);
  doc.setFont("helvetica", "bold");
  doc.text(doc.splitTextToSize(postTitle(a), W - 2 * M - photoW - 52), M + 48, 44);

  const kv = (rows: [string, string][], startY: number, right = M) =>
    autoTable(doc, {
      startY,
      margin: { left: M, right },
      theme: "grid",
      styles: { fontSize: 9, cellPadding: 1.8, valign: "top", textColor: 20, lineColor: 200 },
      columnStyles: { 0: { cellWidth: 58, fontStyle: "bold", fillColor: [244, 246, 250] } },
      body: rows,
    });
  const lastY = () => (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
  const heading = (text: string, y: number) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...NAVY);
    doc.text(text, M, y);
    doc.setTextColor(0);
    return y + 2;
  };

  kv(
    [
      ["1. Name of the Candidate", a.name],
      ["2. Name of the Father / Mother / Husband / Wife", a.relationName],
    ],
    50,
    M + photoW + 4
  );

  kv(
    [
      ["3a. Permanent Address", a.permanentAddress],
      ["3b. Address for correspondence", a.correspondenceAddress],
      ["3c. Mobile No", a.mobile],
      ["3d. e-mail", a.email],
      ["4. Place & Date of Birth", `${a.placeOfBirth}, ${formatDate(a.dateOfBirth)}`],
      ["4a. Nationality", a.nationality],
      ["4b. Religion", a.religion],
      ["4c. Caste", a.caste],
      ["4d. Sex", a.sex],
    ],
    Math.max(lastY(), 39 + photoH) + 4
  );

  let y = heading("5. Educational Qualifications", lastY() + 8);
  autoTable(doc, {
    startY: y,
    margin: { left: M, right: M },
    theme: "grid",
    headStyles: { fillColor: NAVY, fontSize: 8.5 },
    styles: { fontSize: 8.5, cellPadding: 1.6, lineColor: 200 },
    head: [["Degree", "Year", "Name of College", "Name of University/Board", "Percentage of Marks & Grade"]],
    body: QUALIFICATION_DEGREES.map((deg, i) => {
      const q = a.qualifications[i];
      return q.notApplicable
        ? [deg, { content: "Not applicable", colSpan: 4, styles: { textColor: 130, fontStyle: "italic" } }]
        : [deg, q.year, q.college, q.university, q.marks];
    }),
  });

  kv(
    [
      ["5(a). Registration number with date of Registration", `${a.registrationNumber}, ${formatDate(a.registrationDate)}`],
      ["5(b). Name of State Medical Council", a.stateMedicalCouncil],
    ],
    lastY() + 4
  );

  y = heading("6. Details of Teaching experience till date", lastY() + 8);
  autoTable(doc, {
    startY: y,
    margin: { left: M, right: M },
    theme: "grid",
    headStyles: { fillColor: NAVY, fontSize: 8.5 },
    styles: { fontSize: 8.5, cellPadding: 1.6, lineColor: 200 },
    head: [["Designation", "Department", "Institution", "From", "To", "Total experience"]],
    body: EXPERIENCE_DESIGNATIONS.map((des, i) => {
      const e = a.experience[i];
      return e.notApplicable
        ? [des, { content: "Not applicable", colSpan: 5, styles: { textColor: 130, fontStyle: "italic" } }]
        : [des, e.department, e.institution, formatDate(e.from), formatDate(e.to), durationText(e.from, e.to)];
    }),
  });

  kv(
    [
      ["7. Present Place of Working & Designation", a.presentWorking],
      ["8. Total Years of Teaching Experience", a.totalTeachingExperience],
      ["9. Date of appearance in last NMC assessment (UG / PG)", a.lastNmcAssessment],
      ["10. Any other Experience / Administrative experience", a.otherExperience],
      [
        "11. Number of Research articles in Indexed Journals",
        `a. International Journals: ${a.internationalJournals}    National Journals: ${a.nationalJournals}\nb. State / Institutional Journals: ${a.stateJournals}`,
      ],
      [
        "12. Details of other publications",
        `a. Number of Books published: ${a.booksPublished}    b. Number of Chapters in books: ${a.bookChapters}`,
      ],
      ["13. Extra-curricular activities (sports / cultural / medals at university / state / national level)", a.extraCurricular],
      ["14. Any other innovative / initiatives made by the applicant", a.innovations],
      ["15. Any other information the candidate wish to furnish", a.otherInformation],
    ],
    lastY() + 4
  );

  // Declaration
  y = lastY() + 8;
  if (y > 230) {
    doc.addPage();
    y = 20;
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10.5);
  doc.text("DECLARATION", W / 2, y, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  y += 6;
  DECLARATION.forEach((para, i) => {
    const lines = doc.splitTextToSize(para, W - 2 * M - 6);
    if (y + lines.length * 4.2 > 280) {
      doc.addPage();
      y = 20;
    }
    doc.text(`${i + 1}.`, M, y);
    doc.text(lines, M + 6, y);
    y += lines.length * 4.2 + 2;
  });
  if (y > 255) {
    doc.addPage();
    y = 20;
  }
  y += 6;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text(`Date: ${today()}`, M, y);
  doc.text(`Place: ${a.place}`, M, y + 7);
  doc.text("Signature", W - M - 60, y);
  doc.setFont("times", "italic");
  doc.setFontSize(13);
  doc.text(a.signature, W - M - 60, y + 7);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(110);
  doc.text("(typed electronically by the applicant on submission)", W - M - 60, y + 11);
  doc.setTextColor(0);

  // Documents checklist
  doc.addPage();
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text("LIST OF DOCUMENTS TO BE SUBMITTED BY THE APPLICANT", W / 2, 20, { align: "center" });
  autoTable(doc, {
    startY: 26,
    margin: { left: M, right: M },
    theme: "grid",
    headStyles: { fillColor: NAVY, fontSize: 9, halign: "center" },
    styles: { fontSize: 9, cellPadding: 2.2, lineColor: 200, valign: "middle" },
    columnStyles: { 0: { cellWidth: 14, halign: "center" }, 2: { cellWidth: 26, halign: "center", fontStyle: "bold" } },
    head: [["SL. No", "Documents", "Submitted"]],
    body: REQUIRED_DOCUMENTS.map((d, i) => [`${i + 1}.`, d, a.documents[i]]),
  });

  // Footer on every page
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(120);
    doc.text(`Faculty application – ${a.name} – submitted online on ${today()}`, M, 290);
    doc.text(`Page ${p} of ${pages}`, W - M, 290, { align: "right" });
  }

  return doc.output("blob");
}
